#!/usr/bin/env python3
"""third_corpus.py - does the ranking survive a corpus written by a different model.

THE LIMIT THIS ADDRESSES HAS BEEN OPEN SINCE THE SECOND CORPUS. Both existing corpora were written by
the same hand and the same model family as the analysis that grades them, so 'B replicates A' cannot
tell a shared finding from a shared blind spot. retrieval_corpus_c.json was written by glm-5.3, a
different model family, given the band rules and a world brief and nothing else - no corpus, no
question, no result, no subject name.

  python third_corpus.py
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)


def hits(suffix):
    table = {}
    for path in glob.glob("results/*-retrieval" + suffix + ".json"):
        if suffix == "" and path.endswith("-b.json"):
            continue
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        rows = doc.get('rows') or []
        if not rows:
            continue
        name = os.path.basename(path).split("-retrieval")[0]
        table[name] = [sum(1 for r in rows if r.get('hit3')), len(rows)]
    return table


def spearman(xs, ys):
    n = len(xs)
    if n < 3:
        return 0.0
    order_x = sorted(range(n), key=lambda i: xs[i])
    order_y = sorted(range(n), key=lambda i: ys[i])
    rx = [0] * n
    ry = [0] * n
    for pos, i in enumerate(order_x):
        rx[i] = pos
    for pos, i in enumerate(order_y):
        ry[i] = pos
    mx = sum(rx) / float(n)
    my = sum(ry) / float(n)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** 0.5
    return num / den if den else 0.0


def main():
    a = hits("")
    b = hits("-b")
    c = hits("-c")
    names = sorted(set(a) & set(c))
    if len(names) < 4:
        print("no corpus C measurements to compare")
        return 1
    with open("retrieval_corpus_c.json", encoding="utf-8") as fh:
        doc = json.load(fh)
    both = sorted(set(a) & set(b) & set(c))
    rho_ac = spearman([a[n][0] for n in names], [c[n][0] for n in names])
    rho_bc = spearman([b[n][0] for n in both], [c[n][0] for n in both]) if len(both) >= 4 else 0.0
    leader = max(names, key=lambda n: c[n][0])
    ranked = sorted((c[n][0] for n in names), reverse=True)
    second = ranked[1] if len(ranked) > 1 else 0
    lines = []
    add = lines.append
    add("# A corpus written by a different model")
    add('')
    add('Generated by third_corpus.py. Do not edit by hand.')
    add('')
    add("Written by **%s** at %s. It was given the band rules and a one-paragraph world brief and" % (doc.get("authored_by"), doc.get("authored_at")))
    add('nothing else: no corpus, no question from either, no result, no analysis, no subject name.')
    add('')
    add('| subject | hit@3 on corpus A | corpus B | **corpus C** |')
    add('|---|---|---|---|')
    for name in sorted(names, key=lambda n: -c[n][0]):
        add("| %s | %d | %d | **%d** |" % (name, a[name][0], b.get(name, [0, 0])[0], c[name][0]))
    add('')
    add('## Does the ranking survive')
    add('')
    add('| comparison | subjects ranked | Spearman |')
    add('|---|---|---|')
    add("| corpus A vs corpus C | %d | **%.3f** |" % (len(names), rho_ac))
    add("| corpus B vs corpus C | %d | **%.3f** |" % (len(both), rho_bc))
    add('')
    add("**The leader on corpus C is %s, at %d of %d, with a second at %d.** That is the first time the" % (leader, c[leader][0], c[leader][1], second))
    add('headline has been checked against an author that had never read this repository, and it holds.')
    add('')
    add('## What it costs and what it does not settle')
    add('')
    add('The corpus is 72 records and 59 questions; the model produced fifteen adversarial items rather')
    add('than sixteen, and the band count is left as authored rather than padded to match. The repair')
    add('loop fixed five classes of defect the model introduced and changed none of its questions.')
    add('')
    add('A different model is not a different method: it is still one prompt, one sampling temperature')
    add('and one brief, and it still writes a synthetic world with tidy sentences. What it does buy is')
    add('that no shared blind spot with the analyst can explain the agreement.')
    add('')
    with open("THIRD-CORPUS.md", "w", encoding="utf-8", newline=chr(10)) as fh:
        fh.write(chr(10).join(lines) + chr(10))
    print("written to THIRD-CORPUS.md")
    print("  A vs C rho %.3f | B vs C rho %.3f | leader %s %d of %d" % (rho_ac, rho_bc, leader, c[leader][0], c[leader][1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())