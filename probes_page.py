#!/usr/bin/env python3
"""probes_page.py - the one page here with no generator, checked against the pins that do exist.

docs/probes.md IS AN ARGUMENT, NOT A TABLE, and its transcripts carry timings - which cannot be
regenerated by anybody. Everything else in them can be. The probe names, their order and their verdicts
are exactly what expected-control.json and expected.json pin, and the probe job in CI runs both subjects
against those pins on every push. So the page is compared with the pins rather than re-run: it is the
strongest thing that can be said about a transcript nobody can produce again.

    python probes_page.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)

ROW = re.compile(r"^(\w+)\s+(PASS|FAIL|UNKNOWN)\s+([\d.]+s)\s")


def blocks(path):
    """Every fenced block in a page, with the command line that opened it."""
    fence = chr(96) * 3
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    out = []
    for m in re.finditer(re.escape(fence) + r".*?" + re.escape(fence), text, flags=re.S):
        lines = m.group(0).split(chr(10))
        body = [l for l in lines[1:] if l.strip() and l.strip() != fence]
        if body:
            out.append((body[0], body))
    return out


def transcript(path, marker):
    """The probe rows and the failure line of the block whose command mentions marker."""
    for command, body in blocks(path):
        if marker not in command:
            continue
        rows = []
        failed = None
        for line in body:
            m = ROW.match(line.strip())
            if m:
                rows.append((m.group(1), m.group(2)))
            elif "probe(s) failed" in line:
                failed = int(re.match(r"(\d+)", line.strip()).group(1))
        return rows, failed
    return None, None


def compare(path, marker, pin_path):
    rows, failed = transcript(path, marker)
    if rows is None:
        return ["%s has no transcript for %s" % (path, marker)], 0
    with open(pin_path, encoding="utf-8") as fh:
        pin = json.load(fh)
    bad = []
    if [n for n, _v in rows] != list(pin):
        missing = [n for n in pin if n not in [r[0] for r in rows]]
        extra = [r[0] for r in rows if r[0] not in pin]
        bad.append("%s: the transcript and %s do not list the same probes (missing %s, extra %s)"
                   % (path, pin_path, missing or "none", extra or "none"))
    for name, verdict in rows:
        if name in pin and pin[name] != verdict:
            bad.append("%s: the page says %s is %s and %s pins %s"
                       % (path, name, verdict, pin_path, pin[name]))
    fails = sum(1 for v in pin.values() if v == "FAIL")
    if failed is not None and failed != fails:
        bad.append("%s: the transcript ends %d probe(s) failed and %s holds %d"
                   % (path, failed, pin_path, fails))
    return bad, len(rows)


def main():
    checks = [("docs/probes.md", "--adapter=control", "expected-control.json"),
              ("README.md", "server-memory/dist/index.js", "expected.json")]
    bad = []
    total = 0
    for path, marker, pin_path in checks:
        if not os.path.isfile(path) or not os.path.isfile(pin_path):
            continue
        problems, n = compare(path, marker, pin_path)
        total += n
        for line in problems:
            print("  " + line)
        bad.extend(problems)
    if bad:
        print("%d disagreement(s) between a transcript and the pin it claims to report" % len(bad))
        return 1
    print("the transcripts in the pages agree with their pins on %d probe rows" % total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
