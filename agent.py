#!/usr/bin/env python3
"""agent.py - four questions about the same eleven subjects, and four different answers.

THE SCORE IS NOT WHAT A CALLER SEES. It credits the right record anywhere in the top three and it credits
silence on a question with no answer. retrieval_mutants.py measured what that costs: a search that puts
its worst match first returns the identical set, and the score does not move by a point while hit@1 falls
from 25 to 15. An agent with a token budget reads the first record and stops, and reads nothing at all
when the memory declines - which is a third question again, and the only one of the three that describes
the thing being bought.

So this report asks all four and puts the answers side by side:

  score   the right record in the top three, plus a correct silence   (what every paired test uses)
  hits    the right record in the top three, answerable questions only
  hit1    the right record first, answerable questions only
  top     the right record first, plus a correct silence              (what a caller actually reads)

  python agent.py
"""
import itertools
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)

import compare
import resolution

BT = chr(96)
CORPORA = [("A", ""), ("B", "-b"), ("C", "-c")]
SHAPES = ("written", "keywords")
METRICS = ("score", "hits", "hit1", "top")


def totals(suffix, shape, metric):
    """Every subject on one ruler."""
    out = []
    for s in resolution.subjects():
        rows = resolution.rows_of(s["slug"], suffix)
        if not rows:
            continue
        vals = [resolution.outcome(r, shape, metric) for r in rows]
        vals = [v for v in vals if v is not None]
        if vals:
            out.append({"label": s["label"], "slug": s["slug"],
                        "got": sum(1 for v in vals if v), "n": len(vals)})
    return out


def by_label(rows):
    return dict((r["label"], r["got"]) for r in rows)


def leaders():
    """Who is first on each ruler, from the totals rather than from the file order."""
    out = []
    for corpus, suffix in CORPORA:
        for shape in SHAPES:
            for metric in METRICS:
                got = totals(suffix, shape, metric)
                if not got:
                    continue
                got.sort(key=lambda r: (-r["got"], r["label"]))
                best = got[0]["got"]
                out.append({"corpus": corpus, "shape": shape, "metric": metric,
                            "best": best, "n": got[0]["n"],
                            "who": [r["label"] for r in got if r["got"] == best]})
    return out


def main(argv=None):
    rulers = leaders()
    people = resolution.subjects()
    present = [s for s in people if resolution.rows_of(s["slug"], "")]
    if len(present) < 4 or not rulers:
        print("not enough subjects with saved rows")
        return 1
    counts = {}
    for r in rulers:
        for who in r["who"]:
            counts.setdefault(who, []).append(r)
    for who, rs in sorted(counts.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        print("%-30s leads %2d of %2d rulers" % (who, len(rs), len(rulers)))
    write_md(os.path.join(HERE, "AGENT.md"), rulers, counts, present)
    return 0


def write_md(path, rulers, counts, present):
    lines = []
    add = lines.append
    add("# What an agent actually reads")
    add("")
    add("Generated by " + BT + "agent.py" + BT + ". Do not edit by hand.")
    add("")
    add("Four questions can be asked of the same saved rows, and this repository has been publishing one")
    add("of them:")
    add("")
    add("| question | the right record in the top three | the right record first | credits a correct silence |")
    add("|---|---|---|---|")
    add("| " + BT + "score" + BT + " | yes | no | yes |")
    add("| " + BT + "hits" + BT + " | yes | no | no |")
    add("| " + BT + "hit1" + BT + " | no | yes | no |")
    add("| " + BT + "top" + BT + " | no | yes | yes |")
    add("")
    add("Every paired test in this repository is computed from " + BT + "score" + BT + ". " + BT + "top" + BT + " is")
    add("what a caller with a token budget sees, and it is the only one of the four that is also what a")
    add("caller experiences: you ask a question, you read the first line back, and when the memory has")
    add("nothing you get nothing.")
    add("")
    add("## Who is first, on each of the four")
    add("")
    add("| corpus | phrasing | metric | top | at the top | margin |")
    add("|---|---|---|---|---|---|")
    for r in sorted(rulers, key=lambda r: (r["corpus"], SHAPES.index(r["shape"]),
                                           METRICS.index(r["metric"]))):
        add("| %s | %s | %s | **%d of %d** | %s | %d |"
            % (r["corpus"], r["shape"], r["metric"], r["best"], r["n"],
               ", ".join(BT + w + BT for w in r["who"]),
               r["best"] - next((x["got"] for x in sorted(totals(dict(CORPORA)[r["corpus"]],
                                                                  r["shape"], r["metric"]),
                                                          key=lambda x: -x["got"])
                                 if x["got"] < r["best"]), r["best"])))
    add("")
    add("### How many rulers each subject is first on")
    add("")
    add("| subject | rulers at the top | of | which |")
    add("|---|---|---|---|")
    for who, rs in sorted(counts.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        marks = ", ".join("%s %s %s" % (r["corpus"], r["shape"], r["metric"]) for r in rs)
        add("| " + BT + who + BT + " | **%d** | %d | %s |" % (len(rs), len(rulers), marks))
    add("")
    write_switch(add, present)
    add("## What this does not say")
    add("")
    add("It does not say the score is wrong to credit the top three. A memory asked to surface candidates")
    add("is doing its job when the right candidate is among them, and a caller that reads all three gets")
    add("what it paid for. It says that the table has one number in it and four questions behind it, and")
    add("that the one published is the only one of the four that no caller experiences directly.")
    add("")
    with open(path, "w", encoding="utf-8", newline=chr(10)) as fh:
        fh.write(chr(10).join(lines) + chr(10))
    print()
    print("written to %s" % path)



def write_switch(add, present):
    """What the choice between the score and the agent reading costs each subject."""
    add("## What the choice of question costs each subject")
    add("")
    add("The same rows, read two ways, on each corpus as written. A positive gap means the subject looks")
    add("better to a caller with a token budget than it does on the score this repository publishes; a")
    add("negative gap means the score has been flattering it.")
    add("")
    for corpus, suffix in CORPORA:
        score = by_label(totals(suffix, "written", "score"))
        top = by_label(totals(suffix, "written", "top"))
        if not score or not top:
            continue
        add("**Corpus %s, as written.**" % corpus)
        add("")
        add("| subject | score | what an agent reads | gap |")
        add("|---|---|---|---|")
        rows = sorted(score.items(), key=lambda kv: -top.get(kv[0], 0))
        for name, s in rows:
            t = top.get(name)
            if t is None:
                continue
            gap = t - s
            mark = ("**%+d**" % gap) if gap else "0"
            add("| " + BT + name + BT + " | %d | %d | %s |" % (s, t, mark))
        add("")
    add("## Where the two readings disagree about a pair")
    add("")
    add("A pair whose verdict changes between the score and the agent reading is a pair whose ranking")
    add("depends on whether the caller reads three records or one. Counted on corpus A as written.")
    add("")
    cells = {}
    for metric in ("score", "top"):
        got = {}
        for a, b in itertools.combinations(present, 2):
            ra, rb = resolution.rows_of(a["slug"], ""), resolution.rows_of(b["slug"], "")
            if ra is None or rb is None:
                continue
            got[tuple(sorted((a["label"], b["label"])))] = resolution.compare_pair(
                ra, rb, "written", metric)
        cells[metric] = got
    common = set(cells["score"]) & set(cells["top"])
    diff = [k for k in common
            if cells["score"][k]["separated"] != cells["top"][k]["separated"]]
    add("%d of %d pairs reach a different verdict, of which these are the first few:" % (len(diff), len(common)))
    add("")
    for k in sorted(diff)[:12]:
        add("- " + BT + k[0] + BT + " vs " + BT + k[1] + BT + ": score p %.3f, agent reading p %.3f"
            % (cells["score"][k]["p"], cells["top"][k]["p"]))
    add("")


if __name__ == "__main__":
    sys.exit(main())
