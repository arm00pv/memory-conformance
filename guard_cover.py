#!/usr/bin/env python3
"""guard_cover.py - is the regeneration guard complete.

THE GUARD WAS WRITTEN AFTER TWO REPORTS HAD DRIFTED, and it did what it was built for: every document
it lists now regenerates from committed results and a byte that moves fails the build. What nothing
checked was the list itself. A document added to this repository after the guard was written would
carry the same "Do not edit by hand" sentence, be edited by hand anyway, and pass every check -
because the check only ever looked at the files it had been told about. THIRD-CORPUS.md was in
exactly that position for four phases: generated, committed, never re-run by the guard.

So this reads the claim in each document ("Generated by X. Do not edit by hand."), reads the guard
out of the workflow file, and compares the two sets. A document whose generator is not listed fails
here. Running it found the one document that had escaped, and it will find the next one.

    python guard_cover.py
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)

WORKFLOW = os.path.join(".github", "workflows", "ci.yml")
STEP = "the generated reports must match their generators"
BANNER = re.compile(r"Generated by\s+`?([A-Za-z_][\w.-]*\.py)`?")
RAN = re.compile(r"python\s+([\w./-]+\.py)")

# TWO TOOLS GENERATE A BLOCK RATHER THAN A DOCUMENT, and they are named here so that the second
# direction of this check can be strict: a guard line that regenerates nothing at all is a stale line
# claiming to be a check, and it is exactly as invisible as a document that was never added.
BLOCK_ONLY = {
    "matrix.py": "prints the block sync_readme.py writes",
    "sync_readme.py": "fills one fenced block inside a page that is otherwise written by hand",
}


def documents():
    """Every markdown file, and the tool it says generated it - if it says anything at all."""
    out = {}
    for path in sorted(glob.glob("*.md") + glob.glob("docs/*.md")):
        if path.lower() in ("quickstart.md",):
            continue
        with open(path, encoding="utf-8") as fh:
            head = fh.read(4000)
        found = BANNER.search(head)
        if found:
            out[path.replace(os.sep, "/")] = found.group(1)
    return out


def guard(path=None):
    """The tools the guard re-runs, read out of the workflow rather than remembered."""
    path = path or WORKFLOW
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    start = None
    for i, line in enumerate(lines):
        if STEP in line:
            start = i
            break
    if start is None:
        return None
    tools, seen_run = [], False
    for line in lines[start + 1:]:
        if line.strip().startswith("- name:") and seen_run:
            break
        if "git diff --exit-code" in line:
            seen_run = True
            break
        found = RAN.search(line)
        if found:
            tools.append(os.path.basename(found.group(1)))
    return tools


def main(argv=None):
    # THE WORKFLOW IS AN ARGUMENT SO THAT THE CHECK CAN BE MADE TO FAIL ON PURPOSE. A check nobody has
    # seen fail is a check nobody knows the shape of, and this one is easy to disarm: point it at a
    # workflow with one line too many and it must complain.
    path = WORKFLOW
    for arg in (argv or [])[1:]:
        if arg.startswith("--workflow="):
            path = arg.split("=", 1)[1]
    docs = documents()
    tools = guard(path)
    if not docs:
        print("no document in this repository claims to be generated, which cannot be right")
        return 1
    if tools is None:
        print("could not find the guard step in " + path + " - refusing to report a pass")
        return 1
    running = set(tools)
    missing = sorted((path, tool) for path, tool in docs.items() if tool not in running)
    print("%d documents say they are generated by a tool" % len(docs))
    print("%d tools are re-run by the guard in %s" % (len(running), path))
    print("%d documents are outside the guard" % len(missing))
    for path, tool in missing:
        print("  NOT COVERED  %-28s %s" % (path, tool))
    named = set(docs.values())
    for tool in sorted(BLOCK_ONLY):
        if tool in running:
            print("%s is in the guard and generates a block: %s" % (tool, BLOCK_ONLY[tool]))
    idle = sorted(t for t in running if t not in named and t not in BLOCK_ONLY)
    if idle:
        print("in the guard and generating nothing: " + ", ".join(idle))
    if missing:
        print("a document that is generated and never re-run is a document that can go stale silently")
        return 1
    if idle:
        print("a guard line that regenerates no document is a stale line, not a check")
        return 1
    print("every generated document is re-run from committed results by the guard")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
